/*
 * Program: Calculate Square and Cube of a Number
 * Concept: Arithmetic operations, formatting output
 * Author: C Basics Practice
 */

#include <stdio.h>

int main() {
    int n = 7;

    printf("Number: %d\n", n);
    printf("Square: %d\n", n * n);
    printf("Cube: %d\n", n * n * n);

    return 0;
}
